const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const cp=require('node:child_process');
const html=fs.readFileSync('assets/index.html','utf8');
const scripts=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(x=>x[1]).join('\n');
const syntax=cp.spawnSync('node',['--check'],{input:scripts,encoding:'utf8'});
assert.equal(syntax.status,0,syntax.stderr);
const constants=['flat','trunc','pidOf','frameById'].map(name=>html.split('\n').find(line=>line.startsWith('const '+name+'='))).join('\n');
const functions=html.slice(html.indexOf('function refTokenize('),html.indexOf('function refOpen('));
const ctx=vm.createContext({STATE:{stack:{frames:{},notes:{k:{meta:['appendix','','未知'],body:'正文'}}}}});
vm.runInContext(constants+'\n'+functions,ctx);
assert.equal(vm.runInContext("refResolve('note:k.meta[0]').text",ctx),'appendix');
assert.equal(vm.runInContext("refResolve('note:k.meta[1]').text",ctx),'');
assert.ok(vm.runInContext("refResolve('note:k.meta').err",ctx));
assert.ok(vm.runInContext("refResolve('note:k.meta[0].body').err",ctx));
assert.ok(vm.runInContext("refResolve('note:k.meta[3]').err",ctx));
assert.equal(vm.runInContext("refCandidates('note:k.meta[').opts.length",ctx),3);
assert.equal(vm.runInContext("refCandidates('note:k.meta[').opts[2].desc",ctx),'未知');
console.log('HTML JS syntax + 7 note-meta reference assertions passed');
